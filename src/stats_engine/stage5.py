"""Stage 5 orchestration: approved plan + approved data → verified ``stats_output.json``.

``run_stage5`` is the only way a statistics artifact enters the pipeline. It refuses to run
outside Stage 5, without an approved analysis plan, with unapproved arms, or with arms for
reports not included at full-text assessment. The artifact is recorded in the database
(append-only) before any file is written; Stage 6 can only start once
``Repository.stats_output_problems`` finds nothing wrong (see the Stage 5 → 6 guard).
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

from src.core.enums import Phase
from src.core.exceptions import StatisticsInputError
from src.core.schemas.base import utc_now
from src.core.schemas.stats import StatsOutput, canonical_json
from src.state.repository import Repository
from src.stats_engine.engine import run_plan
from src.stats_engine.report import analysis_csv, analysis_markdown, forest_plot, report_markdown


@dataclass(frozen=True)
class Stage5Artifacts:
    output: StatsOutput
    sha256: str
    directory: Path
    files: dict[str, str]  # relative path -> SHA-256


def run_stage5(
    repo: Repository,
    project_id: str,
    *,
    output_dir: Path,
    generated_at: datetime | None = None,
    render_plots: bool = True,
) -> Stage5Artifacts:
    project = repo.get_project(project_id)
    if project.phase != Phase.STAGE5_META_ANALYSIS.value:
        raise StatisticsInputError(f"Stage 5 cannot run in phase {project.phase}")
    plan = repo.latest_analysis_plan(project_id)
    if plan is None:
        raise StatisticsInputError("no human-approved analysis plan")
    inputs = repo.load_stage5_inputs(project_id)  # validated by run_plan (fail closed)
    output = run_plan(plan, inputs, project_id=project_id, generated_at=generated_at or utc_now())
    sha = repo.record_stats_output(project_id, output)
    files = write_artifacts(output, output_dir, render_plots=render_plots)
    return Stage5Artifacts(output=output, sha256=sha, directory=output_dir, files=files)


MANIFEST = "manifest.json"


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _read_manifest(directory: Path) -> dict[str, Any] | None:
    path = directory / MANIFEST
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(data, dict) or not isinstance(data.get("files"), dict):
        return None
    return data


def _inside(directory: Path, rel: str) -> Path | None:
    """``directory / rel`` if it stays inside ``directory`` (manifest paths are untrusted)."""
    root = directory.resolve()
    path = (directory / rel).resolve()
    return path if path.is_relative_to(root) and path != root else None


def write_artifacts(output: StatsOutput, directory: Path, *, render_plots: bool) -> dict[str, str]:
    """Write the artifacts of ``output`` and retire those of the previous run.

    Session 9 (M4): files generated by the previous run (listed in its ``manifest.json``)
    that this run does not produce — e.g. the forest plot of an analysis that now has no
    data — are deleted, but only if their content still has the hash recorded by that
    manifest, so a file a person edited or any unrelated file is never removed. The new
    ``manifest.json`` is written last, so an interrupted run never leaves a manifest that
    names the new output with files of the old one."""
    directory.mkdir(parents=True, exist_ok=True)
    previous = _read_manifest(directory)
    written: dict[str, str] = {}

    def put(rel: str, text: str) -> None:
        path = directory / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        data = text.encode("utf-8")
        path.write_bytes(data)
        written[rel] = hashlib.sha256(data).hexdigest()

    put("stats_output.json", output.to_canonical_json())
    put("report.md", report_markdown(output))
    for a in output.analyses:
        put(f"tables/{a.analysis_id}.md", analysis_markdown(a))
        put(f"tables/{a.analysis_id}.csv", analysis_csv(a))
        if render_plots:
            svg = forest_plot(a, directory / "plots" / f"{a.analysis_id}.svg")
            if svg is not None:
                written[f"plots/{a.analysis_id}.svg"] = hashlib.sha256(svg.read_bytes()).hexdigest()
    if previous is not None:
        for rel, old_sha in sorted(previous["files"].items()):
            if rel in written or not isinstance(rel, str):
                continue
            path = _inside(directory, rel)
            if path is not None and path.is_file() and _sha256_file(path) == old_sha:
                path.unlink()
    put(MANIFEST, canonical_json({"stats_output_sha256": output.sha256(), "files": written}))
    return written


def verified_plots(directory: Path, stats_sha256: str) -> tuple[list[tuple[str, Path]], list[str]]:
    """Forest plots that belong to the statistics output ``stats_sha256`` (Session 9, M4).

    A plot is returned only if the directory's ``manifest.json`` names that output, the
    stored ``stats_output.json`` has that hash, and the plot file still has the hash the
    manifest records. Files not listed in the manifest are never shown. Returns the plots
    (analysis id, path) and the reasons any plot is withheld."""
    manifest = _read_manifest(directory)
    if manifest is None:
        return [], ["no readable manifest.json for the statistics artifacts"]
    if manifest.get("stats_output_sha256") != stats_sha256:
        return [], [
            "the generated files belong to another statistics output than the current one; "
            "re-run Stage 5 to regenerate them"
        ]
    stored = directory / "stats_output.json"
    if not stored.is_file() or _sha256_file(stored) != stats_sha256:
        return [], ["stats_output.json on disk does not match the current statistics output"]
    plots: list[tuple[str, Path]] = []
    problems: list[str] = []
    for rel, sha in sorted(manifest["files"].items()):
        if not (isinstance(rel, str) and rel.startswith("plots/") and rel.endswith(".svg")):
            continue
        path = _inside(directory, rel)
        if path is None or not path.is_file():
            problems.append(f"{rel} is listed in the manifest but missing")
        elif _sha256_file(path) != sha:
            problems.append(f"{rel} was modified after it was generated; not shown")
        else:
            plots.append((Path(rel).stem, path))
    return plots, problems
